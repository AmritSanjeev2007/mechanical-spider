//! Tunable constants for the display.

/// Overall size of the ImGui interface: text, padding, spacing and panel
/// widths all scale with it. 1.0 is ImGui's default size, 1.5 is 50% larger.
pub const GUI_SCALE: f32 = 1.0;

/// Pixel height of ImGui's built-in font at `GUI_SCALE == 1.0`.
pub const GUI_BASE_FONT_SIZE: f32 = 13.0;
